"""Evidence pack: bilingual case report, captured artefacts with SHA-256 hashes, and a takedown request."""
import hashlib
import html as h
import json
from pathlib import Path


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def takedown_text(r: dict) -> str:
    live = r.get("live", {})
    who, host = live.get("whois", {}), live.get("hosting", {})
    brand = (r.get("impersonated_brand") or {}).get("name", "a UAE entity")
    reasons_en = "\n".join(f"  - {x['en']}" for x in r["reasons"][:6])
    reasons_ar = "\n".join(f"  - {x['ar']}" for x in r["reasons"][:6])
    t = live.get("checked_at", {})
    return f"""To: {who.get('abuse_email') or '[registrar abuse contact]'}; [hosting abuse contact for {host.get('network') or host.get('ip') or 'host'}]
Subject: Phishing takedown request - {r['registered_domain']} impersonating {brand}

Hello,

The following URL hosts a phishing page impersonating {brand} and targeting residents of the United Arab Emirates:

  URL:           {r['url']}
  Final URL:     {live.get('final_url', r['url'])}
  Domain:        {r['registered_domain']} (registrar: {who.get('registrar') or 'unknown'}, created: {who.get('created') or 'unknown'})
  Hosting IP:    {host.get('ip') or 'unknown'} ({host.get('network') or ''} {host.get('country') or ''})
  Observed:      {t.get('utc', '')} UTC / {t.get('uae', '')} UAE time
  Risk score:    {r['risk_score']}/100
  Page SHA-256:  {live.get('html_sha256', 'n/a')}

Indicators:
{reasons_en}

We request suspension of this domain / content under your acceptable use policy. Evidence files with SHA-256 hashes are attached.

---

السادة المحترمون،

يستضيف الرابط أعلاه صفحة تصيد احتيالي تنتحل صفة {(r.get('impersonated_brand') or {}).get('name_ar', 'جهة إماراتية')} وتستهدف سكان دولة الإمارات.
المؤشرات:
{reasons_ar}

نرجو تعليق النطاق أو إزالة المحتوى وفق سياسة الاستخدام لديكم. ملفات الأدلة مرفقة مع بصمات SHA-256.
"""


def report_html(r: dict, files: dict) -> str:
    live = r.get("live", {})
    b = r.get("impersonated_brand") or {}
    color = {"phishing": "#A32D2D", "suspicious": "#854F0B", "safe": "#3B6D11"}[r["verdict"]]
    rows = "".join(f"<tr><td>{h.escape(x['en'])}</td><td dir='rtl'>{h.escape(x['ar'])}</td></tr>" for x in r["reasons"])
    chain = "".join(f"<li>{c['status']} &rarr; {h.escape(c['url'])}</li>" for c in live.get("redirect_chain", []))
    hashes = "".join(f"<tr><td>{h.escape(k)}</td><td><code>{v}</code></td></tr>" for k, v in files.items())
    shot = "<img src='screenshot.png' style='max-width:320px;border:1px solid #ccc'>" if "screenshot.png" in files else "<p>No screenshot captured.</p>"
    t = live.get("checked_at", {})
    return f"""<!DOCTYPE html><html><head><meta charset="utf-8"><title>MIRA case - {h.escape(r['registered_domain'])}</title>
<style>body{{font-family:system-ui,sans-serif;max-width:900px;margin:24px auto;color:#222}}td{{border-top:1px solid #ddd;padding:6px;vertical-align:top}}
table{{border-collapse:collapse;width:100%}}.badge{{color:#fff;background:{color};padding:4px 10px;border-radius:6px}}code{{font-size:11px;word-break:break-all}}</style></head><body>
<h1>MIRA evidence pack <span class="badge">{r['verdict'].upper()} {r['risk_score']}/100</span></h1>
<p><b>URL:</b> {h.escape(r['url'])}<br><b>Final URL:</b> {h.escape(live.get('final_url', r['url']))}<br>
<b>Impersonated brand:</b> {h.escape(b.get('name', '-'))} {('(official: ' + ', '.join(b.get('official_domains', [])) + ')') if b else ''}<br>
<b>Observed:</b> {t.get('utc', '-')} UTC / {t.get('uae', '-')} UAE</p>
<h2>Why it was flagged / أسباب التصنيف</h2><table>{rows}</table>
<h2>Infrastructure</h2><pre>{h.escape(json.dumps({k: live.get(k) for k in ('whois', 'hosting', 'tls', 'content', 'cloaking_similarity')}, ensure_ascii=False, indent=2))}</pre>
<h2>Redirect chain</h2><ol>{chain or '<li>none</li>'}</ol>
<h2>Screenshot</h2>{shot}
<h2>Artefact hashes (SHA-256)</h2><table>{hashes}</table>
<p style="font-size:12px;color:#666">Generated by MIRA. Page captured read-only; no data was submitted to the site.</p></body></html>"""


def write_pack(r: dict, page_html: str, screenshot: Path | None, evidence_dir: Path) -> Path:
    folder = evidence_dir / hashlib.sha256(r["url"].encode()).hexdigest()[:12]
    folder.mkdir(parents=True, exist_ok=True)
    if page_html:
        (folder / "page_capture.html.txt").write_text(page_html, encoding="utf-8")
    (folder / "takedown_request.txt").write_text(takedown_text(r), encoding="utf-8")
    (folder / "case.json").write_text(json.dumps(r, ensure_ascii=False, indent=2, default=str), encoding="utf-8")
    files = {p.name: _sha(p) for p in sorted(folder.iterdir()) if p.name not in ("report.html", "manifest.json")}
    if screenshot and Path(screenshot).exists():
        files["screenshot.png"] = _sha(Path(screenshot))
    (folder / "manifest.json").write_text(json.dumps(files, indent=2), encoding="utf-8")
    (folder / "report.html").write_text(report_html(r, files), encoding="utf-8")
    return folder
